function codePointAt(value: string | undefined): number | undefined {
  return value == null ? undefined : value.codePointAt(0)
}

export function ensureEmojiPresentation(text: string): string {
  if (!text) return text

  const chars = [...text]
  let result = ''

  for (let index = 0; index < chars.length; index += 1) {
    const current = chars[index]
    const code = codePointAt(current)
    const nextCode = codePointAt(chars[index + 1])
    result += current
    if (code == null || !TEXT_DEFAULT_EMOJI.has(code)) continue
    if (nextCode === 0xfe0f || nextCode === 0xfe0e || nextCode === ZERO_WIDTH_JOINER) continue
    result += EMOJI_PRESENTATION_SELECTOR
  }

  return result
}
